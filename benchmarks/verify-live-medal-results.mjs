import assert from 'node:assert/strict';
import {retainLiveMedals} from './live-medal-results.mjs';
import {retainCompetitorBests} from './competitor-bests.mjs';
const definitions=Array.from({length:35},(_,id)=>({name:'Event '+id,unit:'ms',scope:'fixed workflow',comparable:true,observational:false}));
const oldIdentity={product_version:'1',sha256:'AAA'};
const newIdentity={product_version:'2',sha256:'BBB'};
const store={schema:1,events:definitions.map(definition=>({...definition,times:{WinBlaze:100,WinDirStat:200,WizTree:300},samples:{WinBlaze:10,WinDirStat:10,WizTree:10},measurements:{WinBlaze:Array(10).fill(100),WinDirStat:Array(10).fill(200),WizTree:Array(10).fill(300)},result_sources:{WinBlaze:{identity:oldIdentity,source:'previous-batch'}}}))};
const candidate={...store.events[0],times:{...store.events[0].times,WinBlaze:120},measurements:{...store.events[0].measurements,WinBlaze:Array(10).fill(120)}};
const identities={'Event 0':{WinBlaze:{identity:newIdentity,measurement_utc:'2026-10-06T01:00:00Z'}}};
const provenance={batch_started_utc:'2026-10-06T00:00:00Z',source:'new-batch'};
const events=retainLiveMedals(store,definitions,[candidate],identities,provenance);
assert.equal(events.length,35,'Partial reruns must retain all 35 categories');
assert.equal(events[0].times.WinBlaze,120,'WinBlaze uses new validated values even when slower');
assert.equal(events[0].pending_refresh.WinBlaze,false);
assert.equal(events[1].times.WinBlaze,100,'Pending categories retain their last completed value');
assert.equal(events[1].pending_refresh.WinBlaze,true);
assert.equal(events[1].result_sources.WinBlaze.source,'previous-batch');
const short={...candidate,samples:{...candidate.samples,WinBlaze:9},measurements:{...candidate.measurements,WinBlaze:Array(9).fill(50)}};
const pending=retainLiveMedals(store,definitions,[short],identities,provenance);
assert.equal(pending[0].times.WinBlaze,100,'Partial samples cannot replace official ten-run values');
const stale=retainLiveMedals(store,definitions,[candidate],{'Event 0':{WinBlaze:{identity:oldIdentity,measurement_utc:'2026-10-05T01:00:00Z'}}},provenance);
assert.equal(stale[0].times.WinBlaze,100,'An older observation cannot masquerade as a new rerun');
assert(stale[0].pending_refresh.WinBlaze);
assert.throws(()=>retainLiveMedals({schema:2,events:[]},definitions,[],{},provenance),/schema/i);
console.log('PASS: all 35 rows persist, WinBlaze refreshes only from new ten-run evidence, partial/stale values remain source-labelled pending.');
