// Writes the generated benchmark section of README.md (between the
// benchmark:start and benchmark:end markers) from the data embedded in
// benchmarks/CURRENT_COMPARISON.html. Run after render-report.mjs.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '..');
const html = fs.readFileSync(path.join(here, 'CURRENT_COMPARISON.html'), 'utf8');
const match = html.match(/const DATA = (\{.*?\});\n/s);
if (!match) throw new Error('CURRENT_COMPARISON.html has no embedded DATA; run render-report.mjs first');
const data = JSON.parse(match[1]);
const events = data.medals.events;
const products = data.products;

const links = {
  WinBlaze: 'https://github.com/marksmayo/WinBlaze',
  WinDirStat: 'https://windirstat.net',
  WizTree: 'https://diskanalyzer.com',
  'TreeSize Free': 'https://www.jam-software.com/treesize_free',
  SpaceSniffer: 'http://www.uderzo.it/main_products/space_sniffer/',
  Everything: 'https://www.voidtools.com',
  'Directory Report': 'https://www.file-utilities.com',
};
const link = tool => links[tool] ? `[${tool}](${links[tool]})` : tool;

// Category of each event, from its name; the order here is the README order.
const categories = [
  ['Full C: drive', name => /^(Full C: volume|Standard-user ·)/.test(name)],
  ['Datasets: scan + CSV export', name => /scan workflow$/.test(name) && !/^(Full C:|Administrator)/.test(name)],
  ['GUI', name => /^GUI/.test(name)],
  ['Startup', name => /^Startup/.test(name)],
  ['Small folders: CPU, memory and tail latency', name => /^(Empty-file scale|Quick folder|Nonempty dense folder|Feature fixture)/.test(name)],
  ['Administrator (direct MFT read)', name => /^Administrator/.test(name)],
  ['Reliability', name => /^Reliability/.test(name)],
];
const categoryOf = event => (categories.find(([, test]) => test(event.name)) ?? ['Other'])[0];

const integerUnits = new Set(['switches', 'faults', 'objects', 'threads', 'handles']);
function format(value, unit) {
  if (value === null || value === undefined || Number.isNaN(value)) return '—';
  if (integerUnits.has(unit)) return `${Math.round(value).toLocaleString('en-US')}`;
  if (unit === 'ms' && Math.abs(value) >= 10000) return `${(value / 1000).toFixed(1)} s`;
  if (unit === 'ms' && Math.abs(value) >= 1000) return `${(value / 1000).toFixed(2)} s`;
  const magnitude = Math.abs(value);
  const digits = magnitude >= 100 ? 0 : magnitude >= 10 ? 1 : magnitude >= 1 ? 2 : magnitude === 0 ? 0 : 3;
  const text = value.toLocaleString('en-US', { minimumFractionDigits: digits, maximumFractionDigits: digits });
  return `${text} ${unit === '%' ? '%' : unit}`.replace(' %', ' %');
}
const medalMark = { gold: '🥇', silver: '🥈', bronze: '🥉' };

// Standings, overall and per category.
const standings = new Map(products.map(tool => [tool, { gold: 0, silver: 0, bronze: 0 }]));
const byCategory = new Map();
for (const event of events) {
  const category = categoryOf(event);
  if (!byCategory.has(category)) byCategory.set(category, new Map(products.map(tool => [tool, 0])));
  for (const award of event.awards ?? []) {
    if (!award.medal) continue;
    standings.get(award.tool)[award.medal] += 1;
    if (award.medal === 'gold') byCategory.get(category).set(award.tool, byCategory.get(category).get(award.tool) + 1);
  }
}
const order = [...products].sort((a, b) => {
  const x = standings.get(a); const y = standings.get(b);
  return y.gold - x.gold || y.silver - x.silver || y.bronze - x.bronze;
});

const out = [];
out.push('<!-- benchmark:start -->');
out.push('<!-- Generated by `node benchmarks/render-readme.mjs` from benchmarks/CURRENT_COMPARISON.html. Do not edit by hand. -->');
out.push('');
out.push(`Each of the ${events.length} events is a medal event: the median of 10 runs per product, lower is better, and the three best products take gold, silver and bronze.`);
out.push('');
out.push('**Overall**');
out.push('');
out.push('| Product | 🥇 | 🥈 | 🥉 | Total |');
out.push('|---|---:|---:|---:|---:|');
for (const tool of order) {
  const s = standings.get(tool);
  const name = tool === 'WinBlaze' ? `**${link(tool)}**` : link(tool);
  const gold = tool === 'WinBlaze' ? `**${s.gold}**` : `${s.gold}`;
  out.push(`| ${name} | ${gold} | ${s.silver} | ${s.bronze} | ${s.gold + s.silver + s.bronze} |`);
}
out.push('');
out.push('**Gold medals by category**');
out.push('');
const present = categories.map(([name]) => name).filter(name => byCategory.has(name));
out.push(`| Category | Events | ${order.join(' | ')} |`);
out.push(`|---|---:|${order.map(() => '---:').join('|')}|`);
for (const name of present) {
  const count = events.filter(event => categoryOf(event) === name).length;
  const golds = order.map(tool => {
    const value = byCategory.get(name).get(tool);
    return value === 0 ? '·' : tool === 'WinBlaze' ? `**${value}**` : `${value}`;
  });
  out.push(`| ${name} | ${count} | ${golds.join(' | ')} |`);
}
out.push('');

const environment = data.environment ?? {};
const cpu = environment.cpu ?? {};
const storage = environment.dataset_storage ?? {};
const winblazeDates = new Set();
const competitorDates = [];
for (const event of events) {
  for (const [tool, source] of Object.entries(event.result_sources ?? {})) {
    const date = (source?.recorded_utc ?? source?.batch_started_utc ?? '').slice(0, 10);
    if (!date) continue;
    if (tool === 'WinBlaze') winblazeDates.add(date); else competitorDates.push(date);
  }
}
competitorDates.sort();
const gib = bytes => `${Math.round(bytes / 2 ** 30)} GiB`;
out.push(`Measured on ${cpu.name ?? 'an x64 PC'} (${cpu.logical_processors ?? '?'} logical processors), Windows build ${environment.os?.build_number ?? '?'}, ${environment.power?.active_scheme?.includes('Balanced') ? 'Balanced power plan' : 'default power plan'}; datasets on the ${storage.filesystem ?? 'NTFS'} system drive (${storage.size_bytes ? gib(storage.size_bytes) : '?'}). Standard user token unless an event says Administrator. File-system caches are not cleared between runs.`);
out.push('');
out.push(`WinBlaze results: ${[...winblazeDates].sort().slice(-1)[0] ?? 'n/a'}. Competitor results: their best complete 10-run batch for the installed version, recorded ${competitorDates[0] ?? 'n/a'} to ${competitorDates.slice(-1)[0] ?? 'n/a'}.`);
out.push('');

const tableFor = list => {
  const rows = [];
  rows.push(`| Event | ${products.map(tool => (tool === 'WinBlaze' ? `**${tool}**` : tool)).join(' | ')} |`);
  rows.push(`|---|${products.map(() => '---:').join('|')}|`);
  for (const event of list) {
    const awards = new Map((event.awards ?? []).map(award => [award.tool, award]));
    const cells = products.map(tool => {
      const value = event.times?.[tool];
      if (value === undefined || value === null) return '—';
      const award = awards.get(tool);
      let text = format(value, event.unit);
      if (award?.medal === 'gold') text = `**${text}**`;
      if (award?.medal) text = `${text} ${medalMark[award.medal]}`;
      if (event.pending_refresh?.[tool]) text = `${text} †`;
      return text;
    });
    rows.push(`| ${event.name} | ${cells.join(' | ')} |`);
  }
  return rows;
};

for (const name of present) {
  const list = events.filter(event => categoryOf(event) === name);
  out.push(`### ${name}`);
  out.push('');
  const won = list.filter(event => event.awards?.find(award => award.tool === 'WinBlaze')?.medal === 'gold').length;
  out.push(`WinBlaze wins ${won} of ${list.length}.`);
  out.push('');
  out.push('<details><summary>Every event in this category</summary>');
  out.push('');
  out.push(...tableFor(list));
  out.push('');
  out.push('</details>');
  out.push('');
}

const notGold = events.filter(event => event.awards?.find(award => award.tool === 'WinBlaze')?.medal !== 'gold');
out.push('### Events WinBlaze does not win');
out.push('');
if (!notGold.length) {
  out.push('None: WinBlaze takes gold in every event.');
} else {
  out.push('| Event | WinBlaze | Place | Leader |');
  out.push('|---|---:|---:|---|');
  for (const event of notGold) {
    const mine = event.awards.find(award => award.tool === 'WinBlaze');
    const leader = event.awards.find(award => award.place === 1);
    out.push(`| ${event.name} | ${format(mine?.ms, event.unit)} | ${mine ? `${mine.place}${mine.medal ? ` ${medalMark[mine.medal]}` : ''}` : '—'} | ${leader.tool} ${format(leader.ms, event.unit)} |`);
  }
}
out.push('');
out.push('**Bold** is the event winner. 🥇🥈🥉 mark the medal places. — means the product has no result for that event (not supported, not installed for that run, or it failed). † marks a value carried from an earlier batch while that product awaits a refresh.');
out.push('');
out.push('Per-run observations, binary hashes and the offline HTML report are generated locally (`node benchmarks/render-report.mjs`); medal rules and run commands are in [benchmarks/README.md](benchmarks/README.md).');
out.push('<!-- benchmark:end -->');

const readmePath = path.join(repo, 'README.md');
const readme = fs.readFileSync(readmePath, 'utf8');
const start = readme.indexOf('<!-- benchmark:start -->');
const end = readme.indexOf('<!-- benchmark:end -->');
if (start < 0 || end < 0) throw new Error('README.md has no benchmark:start / benchmark:end markers');
const updated = readme.slice(0, start) + out.join('\n') + readme.slice(end + '<!-- benchmark:end -->'.length);
fs.writeFileSync(readmePath, updated);
console.log(`README.md benchmark section: ${events.length} events, WinBlaze ${standings.get('WinBlaze').gold} gold`);
