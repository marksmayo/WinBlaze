import fs from 'node:fs';
import assert from 'node:assert/strict';
import {buildMedalTable,rankMedalEvents} from './medal-table.mjs';
import {retainLiveMedals,medalEvidence} from './live-medal-results.mjs';
import {retainCompetitorBests} from './competitor-bests.mjs';
const read=p=>JSON.parse(fs.readFileSync(new URL(p,import.meta.url),'utf8'));
const baseline=read('./runs/2026-10-05T12-41-15-234Z/report-data.json');
const definitions=read('./original-medal-events.json').events;
const prior=read('./live-medal-results.json');
const partial={...baseline,batch:{...baseline.batch,started_utc:new Date().toISOString()},workflow:[],startup:[],native:[],elevated:[],featurePerformance:[],gui:[],competitors:[]};
const raw=buildMedalTable(partial);
assert(raw.events.length<35,'Raw partial collection reproduces missing rows');
const live=retainLiveMedals(prior,definitions,raw.measurementEvents,medalEvidence(partial,definitions),{batch_started_utc:partial.batch.started_utc});
const identities=Object.fromEntries(['WinDirStat','WizTree'].map(t=>[t,baseline.versions.filter(r=>r.tool===t).at(-1)]));
const selected=retainCompetitorBests(read('./competitor-best-results.json'),live,identities,{});
const scored=rankMedalEvents(selected.events);
assert.equal(scored.events.length,35);
assert(scored.events.every(e=>e.pending_refresh.WinBlaze));
assert(scored.events.every(e=>e.samples.WinBlaze===10));
console.log('PASS: an empty new collection previously drops results; live selection retains all 35 validated rows and marks WinBlaze pending.');
