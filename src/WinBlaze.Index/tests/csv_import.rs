#[test]
fn tsv_roundtrip_preserves_tabs_commas_quotes_and_derived_totals() {
    let csv = "Path,Kind,LogicalBytes,AllocatedBytes,Files,Directories,ModifiedUnixSeconds\n\"Z:\\offline\\comma,\tquote\"\".bin\",File,7,4096,0,0,1767225600\n";
    let tree = winblaze_index::import::read_csv(csv.as_bytes()).unwrap();
    let mut output = Vec::new();
    winblaze_index::export::write_tsv(&tree, &mut output).unwrap();
    assert!(output.starts_with(b"Path\tKind\tLogicalBytes\t"));
    let reopened = winblaze_index::import::read_tsv_with_timezone(
        output.as_slice(),
        |_| unreachable!(),
        winblaze_index::import::CsvTimeZone::Utc,
    )
    .unwrap();
    assert_eq!(reopened.files()[0].name.as_ref(), "comma,\tquote\".bin");
    assert_eq!(reopened.files()[0].size_bytes, 7);
    assert_eq!(reopened.root().unwrap().1.file_count, 1);
}

