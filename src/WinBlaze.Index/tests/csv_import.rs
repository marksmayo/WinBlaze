#[test]
fn rejects_malformed_or_ambiguous_csv_instead_of_loading_a_partial_scan() {
    let header = "Path,Kind,LogicalBytes,AllocatedBytes,Files,Directories,ModifiedUnixSeconds\n";
    for row in ["Z:\\offline,Directory,0,0,0,0,\nZ:\\offline,Directory,0,0,0,0,\n", "\"Z:\\offline\"junk,Directory,0,0,0,0,\n", "Z:\\offline,Directory,nope,0,0,0,\n", "Z:\\offline,Directory,7,4096,1,0,\n", "Z:\\offline,Directory,0,0,0,0,\nZ:\\offline\\a,File,1,1,0,0,\nZ:\\offline\\a,File,1,1,0,0,\n"] {
        assert!(read_csv(format!("{header}{row}").as_bytes()).is_err(), "accepted {row}");
    }
    assert!(read_csv(b"Path,wrong,header\n".as_slice()).is_err());
}
