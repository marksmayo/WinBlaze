#[test]
fn reopens_portable_device_metadata_without_inventing_physical_allocation() {
    let csv=b"Path,Kind,LogicalBytes,AllocatedBytes,Files,Directories,ModifiedUnixSeconds\nMTP:\\Phone,Directory,12,0,1,1,\nMTP:\\Phone\\Pictures,Directory,12,0,1,0,\nMTP:\\Phone\\Pictures\\image.jpg,File,12,0,0,0,\n";
    let tree = winblaze_index::import::read_csv(csv.as_slice()).unwrap();
    assert_eq!(tree.root().unwrap().0.full_path, "MTP:\\Phone");
    assert_eq!(tree.root().unwrap().1.logical_bytes, 12);
    assert_eq!(tree.root().unwrap().1.physical_bytes, 0);
    assert_eq!(
        tree.file_display_path(&tree.files()[0]),
        "MTP:\\Phone\\Pictures\\image.jpg"
    );
}

#[test]
fn external_owner_metadata_survives_reexport_to_json() {
    let csv="Name,Files,Folders,Logical Size,Physical Size,Attributes,Last Change,WinDirStat Attributes,Index,Owner\nZ:\\offline\\a.bin,0,0,7,4096,A,2026-01-01T00:00:00Z,0x20000008,1,DOMAIN\\user\n";
    let tree = winblaze_index::import::read_csv(csv.as_bytes()).unwrap();
    let mut output = Vec::new();
    winblaze_index::export::write_json(&tree, &mut output).unwrap();
    let reopened = winblaze_index::import::read_json(output.as_slice()).unwrap();
    assert_eq!(
        reopened
            .file_export_metadata(reopened.files()[0].id.0)
            .unwrap()
            .owner
            .as_deref(),
        Some("DOMAIN\\user")
    );
}
