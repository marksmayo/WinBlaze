#[test]
fn explicit_wiztree_utc_import_does_not_apply_the_local_timezone() {
    let csv = "File Name,Size,Allocated,Modified,Attributes,Files,Folders\nZ:\\offline\\a.bin,7,4096,2026/01/01 00:00:00,32,0,0\n";
    let tree = winblaze_index::import::read_csv_with_timezone(
        csv.as_bytes(),
        |_| panic!("UTC input must not call local conversion"),
        winblaze_index::import::CsvTimeZone::Utc,
    )
    .unwrap();
    assert_eq!(tree.files()[0].modified_utc(), Some(134116992000000000));
}
#[test]
fn reopens_a_winblaze_csv_snapshot_without_reading_the_original_files() {
    let input = "Path,Kind,LogicalBytes,AllocatedBytes,Files,Directories,ModifiedUnixSeconds\r\n\"Z:\\offline\",Directory,7,4096,1,0,123\r\n\"Z:\\offline\\日本,\"\"report\"\".bin\",File,7,4096,0,0,123\r\n";
    let tree = read_csv(input.as_bytes()).unwrap();
    let (_, totals) = tree.root().unwrap();
    assert_eq!(
        (
            totals.file_count,
            totals.logical_bytes,
            totals.physical_bytes
        ),
        (1, 7, 4096)
    );
    let mut out = Vec::new();
    write_csv(&tree, &mut out).unwrap();
    assert_eq!(String::from_utf8(out).unwrap(), input);
}
